#!/usr/bin/env node
// Turn an authored block array into a migration that loads it into
// level_materials.lesson_body_blocks.
//
//   node scripts/generate-lesson-blocks-migration.mjs \
//     --json module1_leadership_track_blocks.json \
//     --level 1 \
//     --title "Module 1: The Leader Within" \
//     --lang en
//
// Writes supabase/migrations/<timestamp>_load_<slug>_blocks.sql and stops.
// Nothing touches the database — review the file, then push it.
//
// The generator exists instead of hand-writing the SQL because the payload is
// a large JSON literal that has to be escaped exactly once. Doing that by hand
// is how a stray quote silently truncates a lesson.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const KNOWN = new Set([
  'heading', 'paragraph', 'quote', 'pull_quote_card', 'table', 'video_embed',
  'image', 'reflection_questions', 'scorecard', 'callout', 'divider',
  'assignment_prompt',
]);

function arg(name, fallback = null) {
  const i = process.argv.indexOf(`--${name}`);
  if (i === -1 || i === process.argv.length - 1) return fallback;
  return process.argv[i + 1];
}

const jsonPath = arg('json');
const level = arg('level');
const title = arg('title');
const lang = arg('lang', 'en');

if (!jsonPath || !level || !title) {
  console.error('Missing required argument. Need --json, --level and --title.');
  console.error('Run with --help for an example.');
  process.exit(1);
}
if (lang !== 'en' && lang !== 'fr') {
  console.error(`--lang must be en or fr, got "${lang}"`);
  process.exit(1);
}

const column = lang === 'fr' ? 'lesson_body_blocks_fr' : 'lesson_body_blocks';

let blocks;
try {
  blocks = JSON.parse(readFileSync(jsonPath, 'utf8'));
} catch (err) {
  console.error(`Could not read ${jsonPath}: ${err.message}`);
  process.exit(1);
}

// The column is CHECK-constrained to an array. Catching it here means a clear
// message now rather than a constraint violation halfway through a push.
if (!Array.isArray(blocks)) {
  console.error(`Expected a JSON array of blocks, got ${typeof blocks}.`);
  process.exit(1);
}
if (blocks.length === 0) {
  console.error('Block array is empty — nothing to load.');
  process.exit(1);
}

// Validate before generating. An unknown type is a warning, not an error: the
// renderer skips what it cannot draw, so a forward-looking block should not
// block the whole load. A missing id or type is fatal, because the parser
// drops those silently and the lesson would come out short with no clue why.
const seenIds = new Set();
const warnings = [];
blocks.forEach((b, i) => {
  if (typeof b !== 'object' || b === null || Array.isArray(b)) {
    console.error(`Block ${i} is not an object.`);
    process.exit(1);
  }
  if (typeof b.type !== 'string' || !b.type) {
    console.error(`Block ${i} has no "type".`);
    process.exit(1);
  }
  if (typeof b.id !== 'string' || !b.id) {
    console.error(`Block ${i} (${b.type}) has no "id".`);
    process.exit(1);
  }
  if (seenIds.has(b.id)) {
    console.error(`Duplicate block id "${b.id}" at index ${i}.`);
    process.exit(1);
  }
  seenIds.add(b.id);
  if (!KNOWN.has(b.type)) warnings.push(`  block ${i}: unknown type "${b.type}"`);
  if (b.type === 'video_embed' && /^https?:/i.test(b.youtubeId ?? '')) {
    console.error(`Block ${i}: youtubeId must be a bare id, not a URL.`);
    process.exit(1);
  }
  if (b.type === 'image' && typeof b.alt !== 'string') {
    console.error(`Block ${i}: image needs an "alt" (empty string = decorative).`);
    process.exit(1);
  }
});

const counts = blocks.reduce((acc, b) => {
  acc[b.type] = (acc[b.type] ?? 0) + 1;
  return acc;
}, {});

// Single quotes doubled — the one escape a dollar-free SQL string literal
// needs. Applied to the serialised JSON as a whole, so it cannot be applied
// twice to the same value.
const literal = JSON.stringify(blocks, null, 2).replace(/'/g, "''");
const sqlTitle = title.replace(/'/g, "''");

const stamp = new Date()
  .toISOString()
  .replace(/[-:T]/g, '')
  .slice(0, 14);
const slug = title
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, '_')
  .replace(/^_|_$/g, '')
  .slice(0, 40);
const outPath = join('supabase', 'migrations', `${stamp}_load_${slug}_${lang}.sql`);

const sql = `-- Loads authored ${lang.toUpperCase()} blocks into ${column}.
-- Generated by scripts/generate-lesson-blocks-migration.mjs from ${jsonPath}.
-- ${blocks.length} blocks: ${Object.entries(counts).map(([t, n]) => `${n}×${t}`).join(', ')}
--
-- Matches every tenant's copy of this material, the same way the lesson seed
-- did. Re-running overwrites the column with the same value, so it is
-- idempotent.

UPDATE level_materials lm
SET ${column} = '${literal}'::jsonb
FROM level_definitions ld
WHERE lm.level_definition_id = ld.id
  AND ld.level = ${Number(level)}
  AND lm.title = '${sqlTitle}';
`;

mkdirSync(join('supabase', 'migrations'), { recursive: true });
writeFileSync(outPath, sql, 'utf8');

if (warnings.length) {
  console.warn(`Unknown block types (renderer will skip these):\n${warnings.join('\n')}`);
}
console.log(`Wrote ${outPath}`);
console.log(`  ${blocks.length} blocks into ${column}`);
console.log(`  target: level ${level}, title "${title}"`);
console.log('');
console.log('Before pushing, confirm the title matches a real row:');
console.log(`  SELECT COUNT(*) FROM level_materials lm JOIN level_definitions ld`);
console.log(`    ON ld.id = lm.level_definition_id`);
console.log(`   WHERE ld.level = ${Number(level)} AND lm.title = '${sqlTitle}';`);
console.log('  (expect one row per tenant — 4 today)');
